-- ---------------------------------------------------------------------
-- อัปเดตราคากลางมือสองจากประกาศที่ยัง active
-- ---------------------------------------------------------------------
update public.products p
set market_price = round(sub.median_price)
from (
  select product_id, percentile_cont(0.5) within group (order by price) as median_price
  from public.listings
  where status = 'active' and is_deleted = false
  group by product_id
) sub
where p.id = sub.product_id;

-- ตรวจผล
