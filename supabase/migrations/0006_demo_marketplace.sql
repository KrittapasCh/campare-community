       p.market_price          as "ราคากลาง",
       v.active_listings       as "ประกาศที่ขายอยู่",
       p.avg_rating            as "คะแนนเฉลี่ย",
       p.review_count          as "จำนวนรีวิว"
from public.products p
join public.product_market_price v on v.product_id = p.id
order by v.active_listings desc, p.name;
