-- =====================================================================
-- แก้หน่วยของชัตเตอร์ช้าสุดที่หายไปตอนนำเข้า
--
-- ไฟล์ 0011 ตัด ' sec' ทิ้งทั้งสองช่อง ทำให้ค่าอย่าง '30 sec' เหลือ '30'
-- หน้าเว็บเลยแสดงเป็น "30 – 1/8000" ซึ่งอ่านแล้วไม่รู้ว่า 30 คืออะไร
--
-- รูปแบบที่ต้องการ (ให้ตรงกับข้อมูลชุดเดิมจาก seed):
--   shutter_min = '30s'      ← มีหน่วยเพราะเป็นวินาที
--   shutter_max = '1/8000'   ← ไม่ต้องมี เพราะเศษส่วนสื่อว่าเป็นวินาทีอยู่แล้ว
-- =====================================================================

update camera_specs
set shutter_min = shutter_min || 's'
where shutter_min ~ '^[0-9]+(\.[0-9]+)?$';   -- เฉพาะที่เป็นตัวเลขล้วน ยังไม่มีหน่วย

-- ค่าที่เป็นเศษส่วนอยู่แล้ว เช่น '1/2' ไม่ต้องแตะ — สื่อความหมายชัดในตัว

-- ตรวจผล
select shutter_min, shutter_max, count(*)
from camera_specs
where shutter_min is not null
group by shutter_min, shutter_max
order by count(*) desc
limit 10;
